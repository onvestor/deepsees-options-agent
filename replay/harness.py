"""Step 8 -- offline bar replay driving the full pipeline with orders stubbed.

One session at a time, in the order a live session runs them:

    a2 screen -> a1 profile -> signal -> prefilter -> a4 select -> a3 size
    -> stubbed entry -> a5 manage open positions -> deterministic exits
    -> a6 review

Every piece is the production one. The prefilter is
:func:`src.options.prefilter.assemble`, the sizing is
:func:`src.risk.sizing.compute_size`, the agents are the six modules, and the
validator sits between each of them and anything that acts. What is substituted
is the *data* -- bars from a file, a chain from a model, fills from
:mod:`replay.broker` -- and nothing else. A replay that reimplemented the
pipeline would agree with production only by coincidence.

**What a replay can and cannot tell you.**

It can tell you that the pipeline runs end to end, that a skip at one stage
stops the stages after it, that the caps bind, that the deterministic exits
fire, and -- the reason it exists -- whether one set of prompts makes different
decisions from another on identical inputs. That last one is the whole
justification for building it before tuning prompts rather than after.

It cannot tell you whether the strategy makes money. The chain is generated by
:class:`~replay.chain.ChainModel`, so which contracts survive the prefilter and
what they cost are properties of that model. A replay P&L figure is reported
because it is useful for comparing two runs against each other, and it is
reported alongside the model parameters so it can never be quoted as a market
result.

**Cadence is per session, not per poll.** Agent 5 runs every 30 minutes in
production; on daily bars there is one mark per session, so it runs once. That
understates how often a stop would have been tightened and is noted in the
report rather than papered over.
"""
