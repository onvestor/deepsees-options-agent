def _trend_pct(window, sessions: int) -> float:
    if len(window) <= sessions:
        return 0.0
    past = float(window["close"].iloc[-sessions - 1])
    now = float(window["close"].iloc[-1])
    return (now - past) / past if past else 0.0


def stats_rsi(window, limits: Any) -> float:
    from src.signals.indicators import rsi

    series = rsi(window["close"], limits.get_int("signals.rsi_period"))
    value = float(series.iloc[-1])
    return value if value == value else 50.0


def _sessions_between(calendar: TradingCalendar) -> Callable[[date, date], int]:
    """The observation store's ageing function, bound to a calendar."""

    def between(created: date, now: date) -> int:
        return max(0, calendar.sessions_until(now, created))

    return between
